const OCR_INSTRUCTIONS = 'このレシート画像から店舗名と全ての商品・品目を抽出し、以下のJSON形式のみで返してください。\n{"storeName":"店舗名（不明な場合はnull）","date":"YYYY-MM-DD形式の購入日（不明な場合はnull）","total":レシートに印字された支払総額（税込・お会計/合計金額。不明ならnull）の整数,"items":[{item_shape}]}\n各商品のamountは印字された金額をそのままコピーしてください。税計算は不要です。\ntotalには実際の支払合計（税込総額。お会計・合計）を整数で入れ、割引後の最終支払額を優先し、不明ならnullにしてください。\nただし特定の商品に紐づく値引き・割引がある場合は、その商品のamountを値引き後の金額にしてください。正味が印字されていれば（例:「¥216を¥198にしました」）その正味（198）を採用し、値引き額のみ印字されていれば（例:「-18」「値引 -18」）元金額から値引き額を引いた整数を採用してください。値引き行そのものをitemにしたり、マイナス金額のitemを作ったりしないでください。\n商品に紐づかないレシート全体のクーポン・割引は無視し、itemsに反映しないでください。\n小計・合計・税額の集計行はitemsに含めないでください。JSONのみ返してください。'

// taxRate 判定手順の静的ブロック（先頭の \n\n を含む）。
const OCR_TAX_RATE = '\n\n各商品のtaxRate（消費税率, 0/8/10のいずれか）を判定してください。\n1. まず商品の印字金額が税込（内税・総額表示。「内」マークや「税込」表記、または総額表示レシート）か税抜（外税。「外」マーク）かを判定する。税込なら後段で税を足さないためtaxRate=0とする（「8%対象¥…」のような末尾集計は総額表示では税込の小計であり、税を足す信号ではない）。\n2. 税抜（外税）と判定できる場合のみ税率を決める。まずレシート末尾の税区分集計を見て、区分が1つだけ（例:「外8%」のみ）なら軽減マークの読み落としに引きずられず全商品をその率にする。8%対象と10%対象が併記されている場合のみ、各商品行の軽減税率マーク（※, 軽, *, ⑧ 等）を8、標準税率マークを10とし、区分別対象額の合計が集計と整合するよう割り当てる。\n3. 税込か税抜か判別できない場合は8とする。'

// カテゴリ判定ブロック（先頭の \n\n を含む）。{category_list} に番号一覧を差し込む。
